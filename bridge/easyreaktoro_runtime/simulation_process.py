"""Versioned material-flow plans, validated before any equilibrium is solved.

Every output is a finite inventory. Transfer fractions refer to the ORIGINAL
output, never to an already depleted remainder. No output can be spent twice.
Fresh material recipes are the only external input to the process ledger.
"""
from __future__ import annotations
import copy
import math
from .errors import require
from .simulation_reactions import normalize_reaction_stages, reaction_routes, reaction_stage, active_reaction_stages, STAGE_LABELS

PHASES = ('aqueous', 'mineral', 'gas')
SOURCES = {'material', 'previous_point', 'previous_cycle', 'output'}


def migrate_config(raw):
    cfg = copy.deepcopy(raw)
    version = cfg.get('schema_version', 1)
    require(version in (1, 2), 'SIMULATION_VERSION', 'error.simulationInput', '不支持此模拟设置版本')
    if version == 2:
        from .simulation_loops import ensure_route_ids
        normalize_reaction_stages(cfg)
        if not cfg.get('reaction_stages') and isinstance(cfg.get('routes'), list):
            ensure_route_ids(cfg['routes'])
        return cfg
    mode = cfg.get('mode')
    require(mode in {'single_point', 'independent_points', 'closed_path', 'repeated_flushing'},
            'SIMULATION_INPUT', 'error.simulationInput', '旧版计算方式无效')
    points = [{**point, 'id': f'p{i+1}'} for i, point in enumerate(cfg.get('points', []))]
    cfg['points'] = points
    cfg['materials'] = [{'id': 'initial', 'name': '初始物质', 'inputs': cfg.get('inputs', [])}]
    cfg['cycles'] = cfg.get('passes', 1) if mode == 'repeated_flushing' else 1
    cfg['routes'] = []
    for phase in (PHASES if mode == 'repeated_flushing' else ('all',)):
        source = ('previous_cycle' if phase == 'mineral' else 'previous_point') if mode == 'repeated_flushing' else ('previous_point' if mode == 'closed_path' else 'material')
        fraction = 1 / len(points) if points and phase == 'mineral' and mode == 'repeated_flushing' and cfg.get('solid_distribution') == 'total_evenly' else 1
        cfg['routes'].append({'source': source, 'phase': phase, 'material_id': 'initial',
                              'fraction': 1, 'fallback': 'material', 'fallback_fraction': fraction, 'when': 'always'})
    if cfg.get('template_source'):
        cfg['import_provenance'] = cfg['template_source']
        # Labels generated by the old importer are not part of the process model.
        cfg['name'] = {'Basic Sample Template': '平衡计算', 'Water–Rock Interaction Sample Template': '水岩反应'}.get(cfg.get('name'), cfg.get('name'))
    for key in ('mode', 'passes', 'solid_distribution', 'inputs', 'template_source'):
        cfg.pop(key, None)
    cfg['schema_version'] = 2
    from .simulation_loops import ensure_route_ids
    ensure_route_ids(cfg['routes'])
    return cfg


def finite(value, label, lo=0, hi=None):
    require(isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)
            and value >= lo and (hi is None or value <= hi), 'SIMULATION_INPUT', 'error.simulationInput', f'{label} 超出允许范围或不是有限数')
    return float(value)


def resolve_source(route, cycle, index, point_indices):
    source = route['source']
    if source == 'material':
        return None
    if source == 'previous_point':
        return (cycle, index - 1) if index else None
    if source == 'previous_cycle':
        return (cycle - 1, index) if cycle else None
    i = point_indices[route['point_id']]
    return (cycle - route['lag'], i) if cycle >= route['lag'] else None


def route_active(route, cycle):
    return route['when'] == 'always' or (route['when'] == 'first_cycle') == (cycle == 0)


def route_species(route, groups):
    return route['species'] if route['phase'] == 'species' else ([n for names in groups.values() for n in names] if route['phase'] == 'all' else groups[route['phase']])


def validate_material_bases(cfg, groups, plan=None):
    """Only a fresh material transfer can require an unfilled base amount."""
    from .simulation_schedule import missing_amount
    missing = {material['id']: {row['species'] for row in material['inputs'] if missing_amount(row['amount'])}
               for material in cfg['materials']}
    missing = {key: names for key, names in missing.items() if names}
    if not missing:
        return
    if plan is not None:
        # Use the preflight-normalized route defaults and projected point IDs.
        from .simulation_loops import LoopPlan
        plan = LoopPlan(cfg)
    labels = {material['id']: material['name'] for material in cfg['materials']}
    indices = {point['id']: i for i, point in enumerate(cfg['points'])}
    for cycle in range(cfg['cycles']):
        for index in range(len(cfg['points'])):
            if hasattr(plan, 'active') and not plan.active(cycle, index): continue
            assigned = {(target['material_id'], target['species']): value for target, value in plan.assignments(cycle, index)
                        if target['kind'] == 'material_amount'} if plan else {}
            routes = plan.routes(cycle, index) if plan else reaction_routes(cfg, cycle, index)
            for route in routes:
                material = route.get('material_id')
                if material not in missing or not route_active(route, cycle):
                    continue
                if resolve_source(route, cycle, index, indices) is not None:
                    continue
                if route['source'] != 'material' and (cfg.get('reaction_stages') is not None or route['fallback'] != 'material'):
                    continue
                factor = route['fraction'] if route['source'] == 'material' else route['fallback_fraction']
                if factor == 0:
                    continue
                for name in missing[material].intersection(route_species(route, groups)):
                    require(not missing_amount(assigned.get((material, name))), 'SIMULATION_INPUT', 'error.simulationInput',
                            f'第 {cycle+1} 轮、路径位置 {index+1} 需要使用 {labels[material]} 中 {name} 的基础投料量，但该值未填写；请填写基础量或为此处设置投料量')


def validate_process(cfg, groups):
    from .simulation_loops import LoopPlan
    loops = LoopPlan(cfg) if cfg.get('loops') or cfg.get('schedule') else None
    points = cfg['points']
    ids = [p.get('id') for p in points]
    require(all(isinstance(i, str) and i for i in ids) and len(set(ids)) == len(ids), 'SIMULATION_INPUT', 'error.simulationInput', '每个计算点必须有唯一 ID')
    point_indices = {key: i for i, key in enumerate(ids)}
    material_ids = [m.get('id') for m in cfg['materials']]
    require(all(isinstance(x, str) and x for x in material_ids) and len(set(material_ids)) == len(material_ids), 'SIMULATION_INPUT', 'error.simulationInput', '每份物质必须有唯一 ID')
    require(cfg.get('reaction_stages') is not None or isinstance(cfg.get('routes'), list), 'SIMULATION_INPUT', 'error.simulationInput', '请设置物料来源')
    all_names = set(cfg['species'])
    stages = cfg.get('reaction_stages')
    containers = [(STAGE_LABELS[key], stages[key]) for key in active_reaction_stages(len(points), cfg["cycles"], getattr(loops, "lengths", None))] if stages is not None else [(f'第 {i+1} 点', point.get('routes', cfg['routes'])) for i, point in enumerate(points)]
    for label, routes in containers:
        require(isinstance(routes, list) and (0 if stages is not None else 1) <= len(routes) <= 30, 'SIMULATION_INPUT', 'error.simulationInput', f'{label}的物料来源数量无效，最多 30 条')
        for route in routes:
            require(isinstance(route, dict) and route.get('source') in SOURCES and route.get('phase') in {*PHASES, 'all', 'species'}, 'SIMULATION_INPUT', 'error.simulationInput', f'{label}的物料来源规则无效')
            route.setdefault('when', 'always')
            route.setdefault('fallback', 'material')
            route.setdefault('fallback_fraction', 1)
            require(route['when'] in {'always', 'first_cycle', 'after_first_cycle'} and route['fallback'] in {'material', 'none', 'error'}, 'SIMULATION_INPUT', 'error.simulationInput', '规则执行时机或首次来源无效')
            route['fraction'] = finite(route.get('fraction', 1), '传入比例', hi=None if route['source'] == 'material' else 1)
            route['fallback_fraction'] = finite(route['fallback_fraction'], '首次投料倍数')
            if route['source'] == 'material' or stages is None and route['fallback'] == 'material':
                require(route.get('material_id') in material_ids, 'SIMULATION_INPUT', 'error.simulationInput', f'{label}引用的物质配方不存在')
            if route['phase'] == 'species':
                names = route.get('species')
                require(isinstance(names, list) and bool(names) and all(isinstance(n, str) and n in all_names for n in names) and len(set(names)) == len(names), 'SIMULATION_INPUT', 'error.simulationInput', '指定物种分流须选择不重复的系统物种')
            if route['source'] == 'output':
                require(route.get('point_id') in point_indices and type(route.get('lag')) is int and route['lag'] in (0, 1), 'SIMULATION_INPUT', 'error.simulationInput', '输出来源须引用存在的计算点，循环延迟为 0 或 1')
    # Only current and previous cycles can be referenced. Keep two allocation
    # maps even for very large plans; no unbounded preflight bookkeeping.
    used = {}
    for cycle in range(cfg['cycles']):
        for i, point in enumerate(points):
            if hasattr(loops, 'active') and not loops.active(cycle, i): continue
            routes = loops.routes(cycle, i) if loops else reaction_routes(cfg, cycle, i)
            require(stages is None or bool(routes), 'PROCESS_MISSING_SOURCE', 'error.simulationInput', f'{STAGE_LABELS[reaction_stage(cycle, i)]}没有物料来源，请为该位置添加需要参与反应的物料')
            for route in routes:
                if not route_active(route, cycle):
                    continue
                if route['source'] == 'output':
                    require(route['lag'] == 1 or point_indices[route['point_id']] < i, 'PROCESS_FORWARD_REFERENCE', 'error.simulationInput', f'第 {i+1} 点引用了尚未计算的输出；同一循环只能引用前面的点')
                origin = resolve_source(route, cycle, i, point_indices)
                if origin is None:
                    require(stages is None or route['source'] == 'material', 'PROCESS_MISSING_SOURCE', 'error.simulationInput', f'{STAGE_LABELS[reaction_stage(cycle, i)]}没有所选历史输出，请改选配方或已有输出作为物料来源')
                    require(route['source'] == 'material' or route['fallback'] != 'error', 'PROCESS_MISSING_SOURCE', 'error.simulationInput', f'第 {cycle+1} 循环、第 {i+1} 点没有可接收的历史输出，请设置首次来源')
                    continue
                if not route['fraction']:
                    continue
                require(not hasattr(loops, 'active') or loops.active(*origin), 'PROCESS_MISSING_SOURCE', 'error.simulationInput', f'Round {cycle+1}, position {i+1}: the source round ended before the selected source position.')
                allocations = used.setdefault(origin, {})
                for name in route_species(route, groups):
                    allocations[name] = allocations.get(name, 0) + route['fraction']
                    require(allocations[name] <= 1 + 1e-12, 'PROCESS_DOUBLE_SPEND', 'error.simulationInput', f'循环 {origin[0]+1} 的 {points[origin[1]]["label"]} 输出 {name} 被分配了 {allocations[name]:.1%}，超过 100%；请调整分流比例')
        used = {key: value for key, value in used.items() if key[0] >= cycle}


def actual_point(point, cycle):
    temperature = point['temperature_c'] + cycle * point.get('temperature_increment_c', 0)
    pressure = point['pressure_bar'] + cycle * point.get('pressure_increment_bar', 0)
    condition = next((row for row in point.get('round_conditions', []) if row['round'] == cycle + 1), None)
    mode = point.get('pressure_mode', 'fixed')
    if condition is not None:
        temperature, pressure = condition['temperature_c'], condition['pressure_bar']
        mode = condition.get('pressure_mode', 'fixed')
    if mode == 'water_saturation':
        require(math.isfinite(temperature) and 0.01 <= temperature < 373.946,
                'SATURATION_RANGE', 'error.simulationInput',
                f"{point.get('label', '计算点')} 第 {cycle+1} 轮温度为 {temperature:g} °C；纯水饱和蒸汽压需要 0.01 ≤ T < 373.946 °C，请调整温度或改为指定压力")
        import reaktoro as rkt
        pressure = float(rkt.waterSaturationPressureWagnerPruss(temperature + 273.15)) / 1e5
    return {**point, 'temperature_c': temperature, 'pressure_bar': pressure, 'pressure_mode': mode,
            **({'_outer': cycle} if '_inner' in point else {})}


class ProcessInventory:
    def __init__(self, simulation):
        from .simulation_loops import LoopPlan
        self.sim = simulation
        self.cfg = simulation.cfg
        self.loops = getattr(simulation, 'loop_plan', None) or (LoopPlan(self.cfg) if self.cfg.get('schedule') or self.cfg.get('loops') else None)
        self.indices = {p['id']: i for i, p in enumerate(self.cfg['points'])}
        self.outputs = {}
        self.external = simulation.np.zeros(len(simulation.components))
        self.inventory = self.external.copy()
        self.fresh_external = self.external.copy()
        self.reservoir_exchange = self.external.copy()
        self.transfers = []

    def assemble(self, cycle, index):
        from .simulation_reactions import reaction_routes, reaction_stage, STAGE_LABELS
        sim, cfg = self.sim, self.cfg
        amounts, transfers = {}, []
        consumed = sim.np.zeros(len(sim.components))
        fresh = consumed.copy()
        materials = self.loops.material_amounts(sim.materials, sim.database, cycle, index) if self.loops else sim.materials
        routes = self.loops.routes(cycle, index) if self.loops else reaction_routes(cfg, cycle, index)
        for route in routes:
            if not route_active(route, cycle):
                continue
            names = route_species(route, sim.groups)
            origin = resolve_source(route, cycle, index, self.indices)
            if origin is None:
                require(cfg.get('reaction_stages') is None or route['source'] == 'material', 'PROCESS_MISSING_SOURCE', 'error.simulationInput', f'{STAGE_LABELS[reaction_stage(cycle, index)]}没有所选历史输出，请改选配方或已有输出作为物料来源')
                if route['source'] != 'material' and route['fallback'] == 'none':
                    continue
                values = materials[route['material_id']]
                factor = route['fraction'] if route['source'] == 'material' else route['fallback_fraction']
                label = f'material:{route["material_id"]}'
            else:
                values = self.outputs[origin]
                factor = route['fraction']
                label = f'output:{origin[0]+1}:{cfg["points"][origin[1]]["id"]}'
            if not factor:
                continue
            moved = {n: values.get(n, 0) * factor for n in names}
            components = sim.component_amounts(moved)
            if origin is None:
                fresh += components
            else:
                consumed += components
            for n, value in moved.items():
                amounts[n] = amounts.get(n, 0) + value
            transfers.append({'source': label, 'phase': route['phase'], 'fraction': factor, 'amounts_mol': moved})
        return amounts, fresh, consumed, transfers

    def commit(self, cycle, index, output, fresh, consumed, exchange=None):
        sim = self.sim
        self.outputs[(cycle, index)] = output
        if exchange is None:
            engine = getattr(sim, 'constraints', None)
            exchange = engine.exchange if engine is not None else sim.np.zeros(len(sim.components))
        self.fresh_external += fresh
        self.reservoir_exchange += exchange
        self.external += fresh + exchange
        self.inventory += sim.component_amounts(output) - consumed
        error = self.inventory - self.external
        count = self.loops.run_index(cycle, index)+1 if hasattr(self.loops, 'run_index') else cycle * len(self.cfg['points']) + index + 1
        require(float(sim.np.max(sim.np.abs(error))) <= sim.tolerance * count,
                'PROCESS_BALANCE', 'error.simulationFailed', '累计输入与未转移库存的物料账不守恒')
        coordinates = self.loops.common(cycle, index) if self.loops else {}
        return [{**coordinates, 'pass': cycle+1, 'step': index+1, 'component': name, 'input_mol': float(a),
                 'inventory_mol': float(b), 'error_mol': float(d),
                 **({'fresh_input_mol': float(self.fresh_external[i]), 'external_exchange_mol': float(self.reservoir_exchange[i])} if self.cfg.get('equilibrium_constraints') else {})}
                for i, (name, a, b, d) in enumerate(zip(sim.components, self.external, self.inventory, error))]

    def finish_cycle(self, cycle):
        self.outputs = {key: value for key, value in self.outputs.items() if key[0] == cycle}
